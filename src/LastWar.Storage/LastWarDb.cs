using LastWar.Core.Model;
using Npgsql;

namespace LastWar.Storage;

/// <summary>
/// Map scans and power samples. No ORM - raw parameterised SQL stays the most readable thing
/// here. Connections come from Db (Postgres).
///
/// Snapshots are append-only. Nothing is ever overwritten, because the entire point of
/// the power history is being able to ask what changed between any two dates.
/// </summary>
public sealed class LastWarDb(string path)
{
    public string Path { get; } = path;

    NpgsqlConnection Open() => Db.Open(Path);

    public void EnsureSchema()
    {
        if (!Db.FirstTime(Path, "LastWarDb")) return;   // DDL once per process: it takes table locks
        using var c = Open();
        using var cmd = c.CreateCommand();
        cmd.CommandText = """
            CREATE TABLE IF NOT EXISTS map_scan (
                scan_id    BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                server_id  BIGINT NOT NULL,
                taken_at   TEXT    NOT NULL,
                tile_count BIGINT NOT NULL
            );

            CREATE TABLE IF NOT EXISTS map_tile (
                scan_id      BIGINT NOT NULL REFERENCES map_scan(scan_id) ON DELETE CASCADE,
                server_id    BIGINT NOT NULL,
                point_id     BIGINT NOT NULL,
                point_type   BIGINT NOT NULL,
                owner_uid    TEXT    NOT NULL,
                name         TEXT    NOT NULL DEFAULT '',
                alliance_id  TEXT    NOT NULL DEFAULT '',
                alliance_tag TEXT    NOT NULL DEFAULT '',
                hq_level     BIGINT NOT NULL DEFAULT 0,
                build_id     BIGINT NOT NULL DEFAULT 0,
                PRIMARY KEY (scan_id, point_id)
            );
            CREATE INDEX IF NOT EXISTS ix_tile_owner ON map_tile(owner_uid);
            CREATE INDEX IF NOT EXISTS ix_tile_server ON map_tile(server_id);

            -- Cities, alliance buildings and Marshal's Guard traps seen by the same scan (MapFeature).
            CREATE TABLE IF NOT EXISTS map_feature (
                scan_id      BIGINT NOT NULL REFERENCES map_scan(scan_id) ON DELETE CASCADE,
                point_id     BIGINT NOT NULL,
                point_type   BIGINT NOT NULL,
                build_id     BIGINT NOT NULL DEFAULT 0,
                level        BIGINT NOT NULL DEFAULT 0,
                alliance_id  TEXT   NOT NULL DEFAULT '',
                alliance_tag TEXT   NOT NULL DEFAULT '',
                alliance_name TEXT  NOT NULL DEFAULT '',
                label        TEXT   NOT NULL DEFAULT '',
                holder_uid   TEXT   NOT NULL DEFAULT '',
                PRIMARY KEY (scan_id, point_id)
            );

            -- Season 3 greened tiles seen by the scan: gzip of a bitset, bit (pointId - 1) set = green.
            CREATE TABLE IF NOT EXISTS map_green (
                scan_id BIGINT NOT NULL PRIMARY KEY REFERENCES map_scan(scan_id) ON DELETE CASCADE,
                tiles   BIGINT NOT NULL,
                bits    BYTEA  NOT NULL
            );

            CREATE TABLE IF NOT EXISTS power_sample (
                taken_at      TEXT    NOT NULL,
                server_id     BIGINT NOT NULL,
                uid           TEXT    NOT NULL,
                power         BIGINT NOT NULL,
                name          TEXT    NOT NULL DEFAULT '',
                alliance_id   TEXT    NOT NULL DEFAULT '',
                alliance_tag  TEXT    NOT NULL DEFAULT '',
                alliance_name TEXT    NOT NULL DEFAULT '',
                kill_army     BIGINT NOT NULL DEFAULT 0,
                career_level  BIGINT NOT NULL DEFAULT 0,
                hq_level      BIGINT NOT NULL DEFAULT 0,
                point_id      BIGINT NULL,
                source        TEXT    NOT NULL,
                PRIMARY KEY (server_id, uid, taken_at)
            );
            CREATE INDEX IF NOT EXISTS ix_power_taken ON power_sample(server_id, taken_at);
            """;
        cmd.ExecuteNonQuery();
        MovePulsePower(c);
    }

    /// <summary>
    /// Once: the first hourly pulses (2026-09-28 13:31-15:31Z) wrote power rows for only the players
    /// who changed - partial "snapshots" that the pages then read as a whole server (~300 accounts).
    /// They are moved, not deleted, into power_sample_pulse; the same figures are also in player_profile.
    /// </summary>
    static void MovePulsePower(NpgsqlConnection c)
    {
        using var cmd = c.CreateCommand();
        cmd.CommandText = """
            CREATE TABLE IF NOT EXISTS schema_fix (name TEXT PRIMARY KEY, applied_at TEXT NOT NULL, rows BIGINT NOT NULL);
            CREATE TABLE IF NOT EXISTS power_sample_pulse (LIKE power_sample INCLUDING ALL);
            SELECT COUNT(*) FROM schema_fix WHERE name = 'pulse_power_moved';
            """;
        if (Convert.ToInt64(cmd.ExecuteScalar()) > 0) return;
        cmd.CommandText = "SELECT to_regclass('player_profile') IS NOT NULL;";
        var hasProfiles = cmd.ExecuteScalar() is true;
        using var tx = c.BeginTransaction();
        cmd.Transaction = tx;
        cmd.CommandText = hasProfiles ? $"""
            INSERT INTO power_sample_pulse
            SELECT * FROM power_sample WHERE source = 'Profile'
              AND taken_at IN (SELECT DISTINCT taken_at FROM player_profile WHERE source = 'pulse')
            ON CONFLICT DO NOTHING;
            DELETE FROM power_sample p USING power_sample_pulse m
            WHERE m.server_id = p.server_id AND m.uid = p.uid AND m.taken_at = p.taken_at;
            INSERT INTO schema_fix (name, applied_at, rows)
            VALUES ('pulse_power_moved', {Db.NowIso} || 'Z', (SELECT COUNT(*) FROM power_sample_pulse));
            """ : $"INSERT INTO schema_fix (name, applied_at, rows) VALUES ('pulse_power_moved', {Db.NowIso} || 'Z', 0);";
        cmd.ExecuteNonQuery();
        tx.Commit();
    }

    public long InsertMapScan(ServerId server, DateTimeOffset takenAt, IReadOnlyCollection<MapTile> tiles,
        IReadOnlyCollection<MapFeature>? features = null, IReadOnlyCollection<int>? green = null)
    {
        using var c = Open();
        using var tx = c.BeginTransaction();

        using var scan = c.CreateCommand();
        scan.Transaction = tx;
        scan.CommandText = """
            INSERT INTO map_scan (server_id, taken_at, tile_count) VALUES (@s, @t, @n) RETURNING scan_id;
            """;
        scan.Parameters.AddWithValue("@s", server.Value);
        scan.Parameters.AddWithValue("@t", takenAt.ToString("O"));
        scan.Parameters.AddWithValue("@n", tiles.Count);
        var scanId = (long)(scan.ExecuteScalar() ?? 0L);

        using var ins = c.CreateCommand();
        ins.Transaction = tx;
        ins.CommandText = """
            INSERT INTO map_tile
              (scan_id, server_id, point_id, point_type, owner_uid, name, alliance_id, alliance_tag, hq_level, build_id)
            VALUES (@scan, @srv, @pt, @ptype, @uid, @name, @alid, @altag, @hq, @bid)
            ON CONFLICT (scan_id, point_id) DO UPDATE SET server_id = EXCLUDED.server_id, point_type = EXCLUDED.point_type,
              owner_uid = EXCLUDED.owner_uid, name = EXCLUDED.name, alliance_id = EXCLUDED.alliance_id,
              alliance_tag = EXCLUDED.alliance_tag, hq_level = EXCLUDED.hq_level, build_id = EXCLUDED.build_id;
            """;
        var p = ins.Parameters;
        p.AddWithValue("@scan", scanId);
        foreach (var n in new[] { "@srv", "@pt", "@ptype", "@uid", "@name", "@alid", "@altag", "@hq", "@bid" })
            p.Add(new NpgsqlParameter(n, DBNull.Value));

        foreach (var t in tiles)
        {
            p["@srv"].Value = t.Server.Value;
            p["@pt"].Value = t.PointId;
            p["@ptype"].Value = t.PointType;
            p["@uid"].Value = t.OwnerUid.Value;
            p["@name"].Value = t.Name;
            p["@alid"].Value = t.AllianceId;
            p["@altag"].Value = t.AllianceTag;
            p["@hq"].Value = t.HqLevel;
            p["@bid"].Value = t.BuildId;
            ins.ExecuteNonQuery();
        }

        foreach (var f in features ?? [])
        {
            using var fi = c.CreateCommand();
            fi.Transaction = tx;
            fi.CommandText = """
                INSERT INTO map_feature (scan_id, point_id, point_type, build_id, level, alliance_id, alliance_tag, alliance_name, label, holder_uid)
                VALUES (@scan, @pt, @ptype, @bid, @lv, @alid, @altag, @alname, @label, @holder) ON CONFLICT DO NOTHING;
                """;
            fi.Parameters.AddWithValue("@scan", scanId);
            fi.Parameters.AddWithValue("@pt", f.PointId);
            fi.Parameters.AddWithValue("@ptype", f.PointType);
            fi.Parameters.AddWithValue("@bid", f.BuildId);
            fi.Parameters.AddWithValue("@lv", f.Level);
            fi.Parameters.AddWithValue("@alid", f.AllianceId);
            fi.Parameters.AddWithValue("@altag", f.AllianceTag);
            fi.Parameters.AddWithValue("@alname", f.AllianceName);
            fi.Parameters.AddWithValue("@label", f.Label);
            fi.Parameters.AddWithValue("@holder", f.HolderUid);
            fi.ExecuteNonQuery();
        }

        if (green is { Count: > 0 })
        {
            using var gi = c.CreateCommand();
            gi.Transaction = tx;
            gi.CommandText = "INSERT INTO map_green (scan_id, tiles, bits) VALUES (@scan, @n, @b) ON CONFLICT DO NOTHING;";
            gi.Parameters.AddWithValue("@scan", scanId);
            gi.Parameters.AddWithValue("@n", green.Count);
            gi.Parameters.AddWithValue("@b", GreenBits(green));
            gi.ExecuteNonQuery();
        }

        tx.Commit();
        return scanId;
    }

    /// <summary>Point ids -> gzip(bitset); bit (pointId - 1). A 1000x1000 map is 125 KB before gzip.</summary>
    public static byte[] GreenBits(IEnumerable<int> pointIds, int tiles = 1_000_000)
    {
        var bits = new byte[(tiles + 7) / 8];
        foreach (var p in pointIds) { var i = p - 1; if (i >= 0 && i < tiles) bits[i >> 3] |= (byte)(1 << (i & 7)); }
        using var ms = new MemoryStream();
        using (var gz = new System.IO.Compression.GZipStream(ms, System.IO.Compression.CompressionLevel.SmallestSize)) gz.Write(bits);
        return ms.ToArray();
    }
    public int InsertPowerSamples(IReadOnlyCollection<PowerSample> samples)
    {
        using var c = Open();
        using var tx = c.BeginTransaction();
        using var ins = c.CreateCommand();
        ins.Transaction = tx;
        ins.CommandText = """
            INSERT INTO power_sample
              (taken_at, server_id, uid, power, name, alliance_id, alliance_tag, alliance_name,
               kill_army, career_level, hq_level, point_id, source)
            VALUES (@t, @srv, @uid, @pw, @name, @alid, @altag, @alname, @kill, @career, @hq, @pt, @src)
            ON CONFLICT (server_id, uid, taken_at) DO UPDATE SET power = EXCLUDED.power, name = EXCLUDED.name,
              alliance_id = EXCLUDED.alliance_id, alliance_tag = EXCLUDED.alliance_tag, alliance_name = EXCLUDED.alliance_name,
              kill_army = EXCLUDED.kill_army, career_level = EXCLUDED.career_level, hq_level = EXCLUDED.hq_level,
              point_id = EXCLUDED.point_id, source = EXCLUDED.source;
            """;
        var p = ins.Parameters;
        foreach (var n in new[] { "@t", "@srv", "@uid", "@pw", "@name", "@alid", "@altag",
                                  "@alname", "@kill", "@career", "@hq", "@pt", "@src" })
            p.Add(new NpgsqlParameter(n, DBNull.Value));

        var n2 = 0;
        foreach (var s in samples)
        {
            p["@t"].Value = s.TakenAt.ToString("O");
            p["@srv"].Value = s.Server.Value;
            p["@uid"].Value = s.Uid.Value;
            p["@pw"].Value = s.Power;
            p["@name"].Value = s.Name;
            p["@alid"].Value = s.AllianceId;
            p["@altag"].Value = s.AllianceTag;
            p["@alname"].Value = s.AllianceName;
            p["@kill"].Value = s.KillArmy;
            p["@career"].Value = s.CareerLevel;
            p["@hq"].Value = s.HqLevel;
            p["@pt"].Value = (object?)s.PointId ?? DBNull.Value;
            p["@src"].Value = s.Source.ToString();
            ins.ExecuteNonQuery();
            n2++;
        }
        tx.Commit();
        return n2;
    }

    /// <summary>Distinct snapshot timestamps for a server, oldest first.</summary>
    public IReadOnlyList<DateTimeOffset> SnapshotTimes(ServerId server)
    {
        using var c = Open();
        using var cmd = c.CreateCommand();
        cmd.CommandText = "SELECT DISTINCT taken_at FROM power_sample WHERE server_id=@s ORDER BY taken_at;";
        cmd.Parameters.AddWithValue("@s", server.Value);
        using var r = cmd.ExecuteReader();
        var outp = new List<DateTimeOffset>();
        while (r.Read()) outp.Add(DateTimeOffset.Parse(r.GetString(0)));
        return outp;
    }

    public IReadOnlyDictionary<PlayerUid, PowerSample> LoadSnapshot(ServerId server, DateTimeOffset at)
    {
        using var c = Open();
        using var cmd = c.CreateCommand();
        cmd.CommandText = """
            SELECT uid, power, name, alliance_id, alliance_tag, alliance_name,
                   kill_army, career_level, hq_level, point_id, source
            FROM power_sample WHERE server_id=@s AND taken_at=@t;
            """;
        cmd.Parameters.AddWithValue("@s", server.Value);
        cmd.Parameters.AddWithValue("@t", at.ToString("O"));
        using var r = cmd.ExecuteReader();
        var outp = new Dictionary<PlayerUid, PowerSample>();
        while (r.Read())
        {
            var uid = new PlayerUid(r.GetString(0));
            outp[uid] = new PowerSample
            {
                TakenAt = at,
                Server = server,
                Uid = uid,
                Power = r.GetInt64(1),
                Name = r.GetString(2),
                AllianceId = r.GetString(3),
                AllianceTag = r.GetString(4),
                AllianceName = r.GetString(5),
                KillArmy = r.GetInt64(6),
                CareerLevel = (int)r.GetInt64(7),
                HqLevel = (int)r.GetInt64(8),
                PointId = r.IsDBNull(9) ? null : (int)r.GetInt64(9),
                Source = Enum.Parse<PowerSource>(r.GetString(10)),
            };
        }
        return outp;
    }
}
