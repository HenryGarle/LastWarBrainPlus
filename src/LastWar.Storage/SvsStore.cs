using System.Text.Json;
using System.Text.Json.Nodes;

namespace LastWar.Storage;

/// <summary>
/// Warzone Duel ("SvS", cross.throne.*): 8 servers in two groups of 4 (cfg.server_ids "a;a;a;a|b;b;b;b"),
/// three weekly rounds of 1 v 1 points races (Monday to Friday; Sunday's Arms Race and trucks count on Monday), winner of each round invades on Saturday. A snapshot
/// is what an account IN the event sees (schedule, every round's scores, the live round's score breakdown);
/// every snapshot is kept, so later results can be compared with how the servers looked.
/// Strength() is our own read of each server from the data we already collect, for the predictions.
/// </summary>
public sealed class SvsStore(string path)
{
    public void EnsureSchema()
    {
        if (!Db.FirstTime(path, "SvsStore")) return;
        Db.Exec(path, """
            CREATE TABLE IF NOT EXISTS svs_snapshot (
                id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, taken_at TEXT NOT NULL, seen_from BIGINT NOT NULL,
                cfg_id BIGINT NOT NULL, servers TEXT NOT NULL, schedule TEXT NOT NULL, rounds TEXT NOT NULL,
                detail TEXT NOT NULL DEFAULT '', alliances TEXT NOT NULL DEFAULT '');
            CREATE INDEX IF NOT EXISTS ix_svs_cfg ON svs_snapshot (cfg_id, taken_at);
            CREATE TABLE IF NOT EXISTS svs_observation (
                id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, observed_at TEXT NOT NULL, week_start TEXT NOT NULL,
                server_a BIGINT NOT NULL, server_b BIGINT NOT NULL, scores_a TEXT NOT NULL, scores_b TEXT NOT NULL,
                predicted TEXT NOT NULL DEFAULT '', note TEXT NOT NULL DEFAULT '', logged_at TEXT NOT NULL);
            CREATE TABLE IF NOT EXISTS svs_forecast (
                id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, week_start TEXT NOT NULL, server_a BIGINT NOT NULL, server_b BIGINT NOT NULL,
                made_on TEXT NOT NULL, made_at TEXT NOT NULL, model TEXT NOT NULL, curve TEXT NOT NULL, inputs TEXT NOT NULL,
                UNIQUE (week_start, server_a, server_b, made_on));
            CREATE TABLE IF NOT EXISTS svs_setup (
                id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, name TEXT NOT NULL DEFAULT '', start_date TEXT NOT NULL DEFAULT '',
                lineup TEXT NOT NULL, results TEXT NOT NULL DEFAULT '{}', updated_at TEXT NOT NULL);
            -- 2026-10-08: v1 .. v1.2 were made with the wrong race rules - their forecasts go, logged scores get a fresh prediction.
            DELETE FROM svs_forecast WHERE model IN ('v1', 'v1.1', 'v1.2');
            UPDATE svs_observation SET predicted = '' WHERE predicted ~ '"model":"v1(\.1|\.2)?"';
            -- 2026-10-09: v1.4 paced itself on the logged scores (dropped - they are for learning, not correcting).
            DELETE FROM svs_forecast WHERE model = 'v1.4';
            UPDATE svs_observation SET predicted = '' WHERE predicted ~ '"model":"v1\.4"';
            """);
    }

    public void Save(int seenFrom, long cfgId, string servers, string schedule, string rounds, string detail, string alliances)
    {
        EnsureSchema();
        Db.Exec(path, """
            INSERT INTO svs_snapshot (taken_at, seen_from, cfg_id, servers, schedule, rounds, detail, alliances)
            VALUES (@t, @f, @c, @s, @sch, @r, @d, @a);
            """, ("@t", DateTimeOffset.UtcNow.ToString("O")), ("@f", (long)seenFrom), ("@c", cfgId), ("@s", servers),
            ("@sch", schedule), ("@r", rounds), ("@d", detail), ("@a", alliances));
    }

    /// <summary>The newest snapshot of an event that includes any of these servers (servers = ";1967;1981;...;").</summary>
    public Dictionary<string, object?>? Latest(IEnumerable<int> servers)
    {
        EnsureSchema();
        using var c = Db.Open(path);
        foreach (var s in servers)
            if (Db.Rows(c, """
                SELECT taken_at AS "takenAt", seen_from AS "seenFrom", cfg_id AS "cfgId", servers, schedule, rounds, detail, alliances
                FROM svs_snapshot WHERE servers LIKE @s ORDER BY id DESC LIMIT 1;
                """, ("@s", $"%;{s};%")).FirstOrDefault() is { } r) return r;
        return null;
    }

    /// <summary>
    /// Each server's strength from what we hold: players from it, top-100 hero power summed, how many were active in
    /// the last 3 days (logged in, donated or chatted), and their power. Servers we do not track come back with 0s.
    /// </summary>
    public List<Dictionary<string, object?>> Strength(IReadOnlyCollection<int> servers)
    {
        using var c = Db.Open(path);
        return Db.Rows(c, $"""
            WITH p AS (
                SELECT pl.server, pl.uid, pl.alliance_id, COALESCE(pl.hero, 0) AS hero, COALESCE(pl.power, 0) AS power,
                       row_number() OVER (PARTITION BY pl.server ORDER BY COALESCE(pl.hero, 0) DESC) AS rk,
                       (pa.last_active_at <> '' AND pa.last_active_at >= {Db.AgoIso("3 days")}) AS active
                FROM player_latest pl LEFT JOIN player_activity pa ON pa.uid = pl.uid
                WHERE pl.server = ANY(@s)),
            s AS (
                SELECT server, count(*) AS players,
                       SUM(CASE WHEN rk <= 100 THEN hero ELSE 0 END) AS "top100Hero",
                       SUM(CASE WHEN rk <= 20 THEN hero ELSE 0 END) AS "top20Hero",
                       count(*) FILTER (WHERE active) AS active,
                       MAX(hero) AS "top1Hero",
                       SUM(CASE WHEN active THEN hero ELSE 0 END) AS "activeHero",
                       SUM(CASE WHEN active THEN power ELSE 0 END) AS "activePower"
                FROM p GROUP BY server),
            -- boss 1st place: the 5 strongest players active in the last 3 days
            t AS (
                SELECT server, string_agg(hero::text, ';' ORDER BY hero DESC) AS heroes
                FROM (SELECT server, hero, row_number() OVER (PARTITION BY server ORDER BY hero DESC) AS r FROM p WHERE active) x
                WHERE r <= 5 GROUP BY server),
            -- duel match-ups: alliances with 10+ members active in the last 3 days
            al AS (
                SELECT server, count(*) AS n
                FROM (SELECT server, alliance_id FROM p WHERE active AND alliance_id <> '' GROUP BY 1, 2 HAVING count(*) >= 10) x
                GROUP BY server)
            SELECT s.*, COALESCE(t.heroes, '') AS "topHeroes", COALESCE(al.n, 0) AS alliances
            FROM s LEFT JOIN t ON t.server = s.server LEFT JOIN al ON al.server = s.server;
            """, ("@s", servers.Select(x => (long)x).ToArray()));
    }
    /// <summary>The newest snapshot of one event (by the game's cfg id).</summary>
    public Dictionary<string, object?>? LatestOf(long cfgId)
    {
        EnsureSchema();
        using var c = Db.Open(path);
        return Db.Rows(c, """
            SELECT taken_at AS "takenAt", seen_from AS "seenFrom", cfg_id AS "cfgId", servers, schedule, rounds, detail, alliances
            FROM svs_snapshot WHERE cfg_id = @c ORDER BY id DESC LIMIT 1;
            """, ("@c", cfgId)).FirstOrDefault();
    }

    /// <summary>Warzone Duels from the game's table (lw_zone_war type 8, kept by servers.tables) holding any of these servers, or one by id; newest first.</summary>
    public List<Dictionary<string, object?>> Events(IReadOnlyCollection<int> servers, long? cfgId = null, int limit = 60)
    {
        EnsureSchema();
        using var c = Db.Open(path);
        return Db.Rows(c, """
            SELECT w.id, w.open_time AS "openTime", w.end_time AS "endTime", w.server_ids AS "serverIds",
                   (SELECT count(*) FROM svs_snapshot s WHERE s.cfg_id = w.id) AS reads
            FROM game_zone_war w
            WHERE w.type = 8 AND (w.id = @id OR (@id = 0 AND ';' || replace(w.server_ids, '|', ';') || ';' LIKE ANY(@s)))
            ORDER BY w.open_time DESC, w.id LIMIT @n;
            """, ("@id", cfgId ?? 0L), ("@s", servers.Select(x => $"%;{x};%").ToArray()), ("@n", (long)limit));
    }

    /// <summary>
    /// Capitals taken between these servers in a window: a president from another of them (president table, intel)
    /// whose term starts inside it - the Saturday invasion succeeding. A server that won invasion rights but did not
    /// take the Capitol leaves no trace. "by" is occupy_server (the attacking side) when the game gives it, else the
    /// president's own server (a transferred player keeps his old uid suffix).
    /// </summary>
    public List<Dictionary<string, object?>> Captures(string from, string to, IReadOnlyCollection<int> servers)
    {
        using var c = Db.Open(path);
        return Db.Rows(c, """
            SELECT server, by, became_at AS at, name, tag FROM (
                SELECT p.server, COALESCE(NULLIF(p.occupy_server, 0), right(p.uid, 6)::int) AS by, p.became_at, p.name, p.tag
                FROM president p
                WHERE p.became_at >= @f AND p.became_at < @t AND p.server = ANY(@s) AND p.uid ~ '^[0-9]{7,}$' AND right(p.uid, 6)::int <> p.server) x
            WHERE by = ANY(@s) ORDER BY became_at;
            """, ("@f", from.Replace(' ', 'T')), ("@t", to.Replace(' ', 'T')), ("@s", servers.Select(x => (long)x).ToArray()));
    }

    /// <summary>Event windows (open time) where a live read showed servers the table put in another event: the game re-drew that pool.</summary>
    public HashSet<string> RedrawnWindows()
    {
        EnsureSchema();
        using var c = Db.Open(path);
        static string Set(string ids) => string.Join(";", ids.Split([';', '|'], StringSplitOptions.RemoveEmptyEntries).Select(int.Parse).Order());
        return Db.Rows(c, "SELECT DISTINCT w.open_time AS o, w.server_ids AS t, s.servers AS r FROM svs_snapshot s JOIN game_zone_war w ON w.id = s.cfg_id;")
            .Where(r => Set((string)r["t"]!) != Set((string)r["r"]!)).Select(r => (string)r["o"]!).ToHashSet();
    }

    /// <summary>
    /// Duels set up by hand (Henry, 2026-10-08): lineup "A1;A2;A3;A4|B1;B2;B3;B4" in round-1 order (A1 v A2, A3 v A4,
    /// B1 v B2, B3 v B4 - the later rounds follow from who wins), results {"round:low-high": winner} as entered.
    /// </summary>
    public List<Dictionary<string, object?>> Setups()
    {
        EnsureSchema();
        using var c = Db.Open(path);
        return Db.Rows(c, """SELECT id, name, start_date AS "start", lineup, results, updated_at AS "updatedAt" FROM svs_setup ORDER BY start_date DESC, id DESC;""");
    }

    public long SaveSetup(long? id, string name, string start, string lineup, string results)
    {
        EnsureSchema();
        using var c = Db.Open(path);
        var now = DateTimeOffset.UtcNow.ToString("O");
        if (id is > 0)
        {
            Db.Exec(path, "UPDATE svs_setup SET name = @n, start_date = @s, lineup = @l, results = @r, updated_at = @u WHERE id = @id;",
                ("@n", name), ("@s", start), ("@l", lineup), ("@r", results), ("@u", now), ("@id", id.Value));
            return id.Value;
        }
        return Convert.ToInt64(Db.Rows(c, "INSERT INTO svs_setup (name, start_date, lineup, results, updated_at) VALUES (@n, @s, @l, @r, @u) RETURNING id;",
            ("@n", name), ("@s", start), ("@l", lineup), ("@r", results), ("@u", now))[0]["id"]);
    }

    public void DeleteSetup(long id)
    {
        EnsureSchema();
        using var c = Db.Open(path);
        Db.Exec(path, "DELETE FROM svs_setup WHERE id = @id;", ("@id", id));
    }

    /// <summary>The model's inputs for one server, from Strength().</summary>
    public SvsModel.Side SideOf(int server)
    {
        var r = Strength([server]).FirstOrDefault();
        double N(string k) => r?[k] is { } v ? Convert.ToDouble(v) : 0;
        var top = (r?["topHeroes"] as string ?? "").Split(';', StringSplitOptions.RemoveEmptyEntries).Select(v => double.Parse(v, System.Globalization.CultureInfo.InvariantCulture)).ToArray();
        return new SvsModel.Side(N("top1Hero"), N("top100Hero"), N("activeHero"), top, N("alliances"));
    }

    /// <summary>
    /// What the model says for a pair after <paramref name="days"/> of the race, and at the end of it, with the inputs used.
    /// </summary>
    public Dictionary<string, object?> Predict(int a, int b, double days)
    {
        var (sa, sb) = (SideOf(a), SideOf(b));
        var now = SvsModel.Predict(sa, sb, days);
        var end = SvsModel.Predict(sa, sb, SvsModel.RaceDays);
        return new()
        {
            ["a"] = a, ["b"] = b, ["days"] = days, ["model"] = SvsModel.Version,
            ["nowA"] = now.A, ["nowB"] = now.B, ["endA"] = end.A, ["endB"] = end.B,
            ["inputs"] = new Dictionary<string, object?> { ["a"] = sa, ["b"] = sb },
        };
    }

    /// <summary>
    /// Scores as seen in the game (Weekly Results, six metrics per side, in the game's order) at a moment, with what we
    /// predicted for that same moment stored beside them - so the model can be judged and re-fitted later.
    /// </summary>
    public long AddObservation(string observedAt, string weekStart, int a, int b, double[] scoresA, double[] scoresB, string note)
    {
        EnsureSchema();
        var days = (DateTimeOffset.Parse(observedAt) - DateTimeOffset.Parse(weekStart + "T00:00:00Z")).TotalDays;
        var predicted = System.Text.Json.JsonSerializer.Serialize(Predict(a, b, days));
        using var c = Db.Open(path);
        return Convert.ToInt64(Db.Rows(c, """
            INSERT INTO svs_observation (observed_at, week_start, server_a, server_b, scores_a, scores_b, predicted, note, logged_at)
            VALUES (@o, @w, @a, @b, @sa, @sb, @p, @n, @l) RETURNING id;
            """, ("@o", observedAt), ("@w", weekStart), ("@a", (long)a), ("@b", (long)b),
            ("@sa", System.Text.Json.JsonSerializer.Serialize(scoresA)), ("@sb", System.Text.Json.JsonSerializer.Serialize(scoresB)),
            ("@p", predicted), ("@n", note), ("@l", DateTimeOffset.UtcNow.ToString("O")))[0]["id"]);
    }

    public List<Dictionary<string, object?>> Observations()
    {
        EnsureSchema();
        using var c = Db.Open(path);
        // A row added without a prediction (by hand, in SQL) gets one now - from today's data, so a little less fair than one made at the time.
        foreach (var r in Db.Rows(c, "SELECT id, observed_at, week_start, server_a, server_b FROM svs_observation WHERE predicted = '';"))
        {
            var days = (DateTimeOffset.Parse((string)r["observed_at"]!) - DateTimeOffset.Parse((string)r["week_start"]! + "T00:00:00Z")).TotalDays;
            var p = Predict(Convert.ToInt32(r["server_a"]), Convert.ToInt32(r["server_b"]), days);
            p["late"] = true;
            Db.Exec(path, "UPDATE svs_observation SET predicted = @p WHERE id = @id;", ("@p", System.Text.Json.JsonSerializer.Serialize(p)), ("@id", r["id"]));
        }
        return Db.Rows(c, """
            SELECT id, observed_at AS "at", week_start AS "weekStart", server_a AS a, server_b AS b, scores_a AS "scoresA", scores_b AS "scoresB",
                   predicted, note FROM svs_observation ORDER BY observed_at DESC, id DESC;
            """);
    }

    public void DeleteObservation(long id) { EnsureSchema(); Db.Exec(path, "DELETE FROM svs_observation WHERE id = @id;", ("@id", id)); }

    /// <summary>
    /// The model's points for each side by the end of every race day (1..5), counted by the day things happen (SvsModel.EndOfDay);
    /// [day-1][metric]. Day 5 is the final score the invasion rights are decided on.
    /// </summary>
    public (double[][] A, double[][] B) Curve(SvsModel.Side a, SvsModel.Side b)
    {
        var days = Enumerable.Range(1, (int)SvsModel.RaceDays).Select(d => SvsModel.EndOfDay(a, b, d)).ToList();
        return ([.. days.Select(x => x.A)], [.. days.Select(x => x.B)]);
    }

    /// <summary>
    /// Keeps today's forecast for a pair (once a UTC day; the first one of the day stands): the whole 5-day curve and the
    /// inputs it came from. Read back by Forecasts() to see how the estimate moved and how close it was in the end.
    /// </summary>
    public void RecordForecast(string weekStart, int a, int b)
    {
        EnsureSchema();
        var today = DateTime.UtcNow.ToString("yyyy-MM-dd");
        using var c = Db.Open(path);
        if (Db.Rows(c, "SELECT 1 FROM svs_forecast WHERE week_start = @w AND server_a = @a AND server_b = @b AND made_on = @d;",
                ("@w", weekStart), ("@a", (long)a), ("@b", (long)b), ("@d", today)).Count > 0) return;
        var (sa, sb) = (SideOf(a), SideOf(b));
        var (ca, cb) = Curve(sa, sb);
        Db.Exec(path, """
            INSERT INTO svs_forecast (week_start, server_a, server_b, made_on, made_at, model, curve, inputs)
            VALUES (@w, @a, @b, @d, @t, @m, @c, @i) ON CONFLICT DO NOTHING;
            """, ("@w", weekStart), ("@a", (long)a), ("@b", (long)b), ("@d", today), ("@t", DateTimeOffset.UtcNow.ToString("O")),
            ("@m", SvsModel.Version), ("@c", System.Text.Json.JsonSerializer.Serialize(new { a = ca, b = cb })),
            ("@i", System.Text.Json.JsonSerializer.Serialize(new { a = sa, b = sb })));
    }

    public List<Dictionary<string, object?>> Forecasts(string weekStart, int a, int b)
    {
        EnsureSchema();
        using var c = Db.Open(path);
        return Db.Rows(c, """
            SELECT made_on AS "madeOn", made_at AS "madeAt", model, curve, inputs FROM svs_forecast
            WHERE week_start = @w AND server_a = @a AND server_b = @b ORDER BY made_on;
            """, ("@w", weekStart), ("@a", (long)a), ("@b", (long)b));
    }

    /// <summary>Every pair forecast in the last 8 days gets today's forecast too (the daily svs-forecast job).</summary>
    public int RecordRecentForecasts()
    {
        EnsureSchema();
        using var c = Db.Open(path);
        var since = DateTime.UtcNow.AddDays(-8).ToString("yyyy-MM-dd");
        var pairs = Db.Rows(c, "SELECT DISTINCT week_start, server_a, server_b FROM svs_forecast WHERE week_start >= @s;", ("@s", since));
        foreach (var p in pairs) RecordForecast((string)p["week_start"]!, Convert.ToInt32(p["server_a"]), Convert.ToInt32(p["server_b"]));
        return pairs.Count;
    }

    public List<Dictionary<string, object?>> ObservationsOf(string weekStart, int a, int b)
    {
        EnsureSchema();
        using var c = Db.Open(path);
        return Db.Rows(c, """
            SELECT id, observed_at AS "at", scores_a AS "scoresA", scores_b AS "scoresB" FROM svs_observation
            WHERE week_start = @w AND server_a = @a AND server_b = @b ORDER BY observed_at;
            """, ("@w", weekStart), ("@a", (long)a), ("@b", (long)b));
    }
