using System.Text.Json;
using Npgsql;

namespace LastWar.Storage;

/// <summary>
/// Scheduled operations and their run history (the Scheduler in LastWar.Operations runs them).
///
///   schedule_job  one repeating operation: which op, its args, how often, paused or not, next due
///   schedule_run  every run: when, how long, how it ended, its summary and last progress line
/// </summary>
public sealed class ScheduleStore(string path)
{
    public sealed record Job(string Id, string Name, string Op, Dictionary<string, string> Args, int EveryMinutes, bool Enabled, DateTimeOffset? NextAt);

    NpgsqlConnection Open() => Db.Open(path);

    int Exec(string sql, params (string, object?)[] ps)
    {
        using var c = Open();
        using var cmd = c.CreateCommand();
        cmd.CommandText = sql;
        foreach (var (n, v) in ps) cmd.Parameters.AddWithValue(n, v ?? DBNull.Value);
        return cmd.ExecuteNonQuery();
    }

    List<Dictionary<string, object?>> Rows(string sql, params (string, object?)[] ps)
    {
        using var c = Open();
        using var cmd = c.CreateCommand();
        cmd.CommandText = sql;
        foreach (var (n, v) in ps) cmd.Parameters.AddWithValue(n, v ?? DBNull.Value);
        using var r = cmd.ExecuteReader();
        var rows = new List<Dictionary<string, object?>>();
        while (r.Read())
        {
            var row = new Dictionary<string, object?>();
            for (var i = 0; i < r.FieldCount; i++) row[r.GetName(i)] = r.IsDBNull(i) ? null : r.GetValue(i);
            rows.Add(row);
        }
        return rows;
    }

    public void EnsureSchema()
    {
        if (Db.FirstTime(path, "ScheduleStore"))   // DDL once per process: it takes table locks
        Exec("""
            CREATE TABLE IF NOT EXISTS schedule_job (
                id TEXT PRIMARY KEY, name TEXT NOT NULL, op TEXT NOT NULL, args TEXT NOT NULL DEFAULT '{}',
                every_minutes BIGINT NOT NULL, enabled BIGINT NOT NULL DEFAULT 1, next_at TEXT NULL);
            CREATE TABLE IF NOT EXISTS schedule_run (
                id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, job_id TEXT NOT NULL, started_at TEXT NOT NULL, finished_at TEXT NULL,
                state TEXT NOT NULL, summary TEXT NOT NULL DEFAULT '', progress TEXT NOT NULL DEFAULT '', trigger TEXT NOT NULL DEFAULT 'schedule');
            CREATE INDEX IF NOT EXISTS ix_schedule_run_job ON schedule_run(job_id, id);
            """);
        // A run still "running" at start-up was cut off by the server stopping.
        Exec("UPDATE schedule_run SET state = 'interrupted', finished_at = COALESCE(finished_at, started_at) WHERE state = 'running';");
    }

    /// <summary>Adds a job only if its id is new - never changes one the user has edited or paused.</summary>
    public void Seed(string id, string name, string op, Dictionary<string, string> args, int everyMinutes, bool enabled) =>
        Exec("INSERT INTO schedule_job (id, name, op, args, every_minutes, enabled, next_at) VALUES (@i, @n, @o, @a, @e, @en, @t) ON CONFLICT DO NOTHING;",
            ("@i", id), ("@n", name), ("@o", op), ("@a", JsonSerializer.Serialize(args)), ("@e", everyMinutes), ("@en", enabled ? 1 : 0),
            ("@t", DateTimeOffset.UtcNow.ToString("O")));

    public List<Job> Jobs() => Rows("SELECT * FROM schedule_job ORDER BY name;").Select(r => new Job(
        (string)r["id"]!, (string)r["name"]!, (string)r["op"]!,
        JsonSerializer.Deserialize<Dictionary<string, string>>((string)r["args"]!) ?? [],
        Convert.ToInt32(r["every_minutes"]), Convert.ToInt32(r["enabled"]) == 1,
        r["next_at"] is string s && DateTimeOffset.TryParse(s, out var t) ? t : null)).ToList();

    public void SetEnabled(string id, bool on) => Exec("UPDATE schedule_job SET enabled = @e WHERE id = @i;", ("@e", on ? 1 : 0), ("@i", id));
    public void SetNext(string id, DateTimeOffset at) => Exec("UPDATE schedule_job SET next_at = @t WHERE id = @i;", ("@t", at.ToString("O")), ("@i", id));
    /// <summary>Renames a job only if it still has the given old name (the user may have renamed it).</summary>
    public void Rename(string id, string from, string to) =>
        Exec("UPDATE schedule_job SET name = @t WHERE id = @i AND name = @f;", ("@t", to), ("@i", id), ("@f", from));

    public void SetArg(string id, string key, string value)
    {
        var job = Jobs().FirstOrDefault(j => j.Id == id) ?? throw new KeyNotFoundException(id);
        job.Args[key] = value;
        Exec("UPDATE schedule_job SET args = @a WHERE id = @i;", ("@a", JsonSerializer.Serialize(job.Args)), ("@i", id));
    }
    public void SetEvery(string id, int minutes) => Exec("UPDATE schedule_job SET every_minutes = @m WHERE id = @i;", ("@m", minutes), ("@i", id));

    public long StartRun(string jobId, string trigger)
    {
        using var c = Open();
        using var cmd = c.CreateCommand();
        cmd.CommandText = "INSERT INTO schedule_run (job_id, started_at, state, trigger) VALUES (@j, @t, 'running', @tr) RETURNING id;";
        cmd.Parameters.AddWithValue("@j", jobId);
        cmd.Parameters.AddWithValue("@t", DateTimeOffset.UtcNow.ToString("O"));
        cmd.Parameters.AddWithValue("@tr", trigger);
        return (long)cmd.ExecuteScalar()!;
    }

    public void Progress(long runId, string line) => Exec("UPDATE schedule_run SET progress = @p WHERE id = @i;", ("@p", line), ("@i", runId));

    public void FinishRun(long runId, string state, string summary) =>
        Exec("UPDATE schedule_run SET state = @s, summary = @m, finished_at = @t WHERE id = @i;",
            ("@s", state), ("@m", summary), ("@t", DateTimeOffset.UtcNow.ToString("O")), ("@i", runId));

    public List<Dictionary<string, object?>> Runs(string? jobId, int limit) => Rows("""
        SELECT id, job_id AS "jobId", started_at AS "startedAt", finished_at AS "finishedAt", state, summary, progress, trigger
        FROM schedule_run WHERE (CAST(@j AS TEXT) IS NULL OR job_id = @j) ORDER BY id DESC LIMIT @n;
        """, ("@j", jobId), ("@n", limit));
}
